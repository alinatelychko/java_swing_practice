    private void searchButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchButtonActionPerformed
        int fromYear, toYear;

    try {
        fromYear = Integer.parseInt(fromYearField.getText());
        toYear = Integer.parseInt(toYearField.getText());
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Please enter valid years!", "Input Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    DefaultTableModel model = (DefaultTableModel) booksTable.getModel();
    model.setRowCount(0); // Clear table before adding new data

    try (Connection conn = DatabaseConnection.getConnection();
         PreparedStatement stmt = conn.prepareStatement("SELECT * FROM books WHERE publicationYear BETWEEN ? AND ?")) {
        
        stmt.setInt(1, fromYear);
        stmt.setInt(2, toYear);
        
        ResultSet rs = stmt.executeQuery();

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getInt("id"),
                rs.getString("author"),
                rs.getInt("pageCount"),
                rs.getInt("printRun"),
                rs.getInt("publicationYear")
            });
        }
        
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Error fetching data: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_searchButtonActionPerformed

